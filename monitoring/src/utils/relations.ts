/**
 * Pure functions that compute references between Prometheus Operator resources
 * and core Kubernetes objects. They operate on plain JSON so they can be unit
 * tested without a cluster.
 */
import {
  AlertmanagerSpec,
  Labels,
  LabelSelector,
  MonitorNamespaceSelector,
  PrometheusSpec,
  PromRuleGroup,
  PromTarget,
  ThanosRulerSpec,
} from '../types';
import { matchesLabelSelector, monitorNamespaceMatches } from './selectors';

export interface ObjectRef {
  metadata: { name: string; namespace?: string; labels?: Labels; uid?: string };
}

/** Kinds a Prometheus-like workload can select. */
export type SelectableKind =
  | 'ServiceMonitor'
  | 'PodMonitor'
  | 'Probe'
  | 'ScrapeConfig'
  | 'PrometheusRule'
  | 'AlertmanagerConfig';

const SELECTOR_FIELDS: Record<SelectableKind, [string, string]> = {
  ServiceMonitor: ['serviceMonitorSelector', 'serviceMonitorNamespaceSelector'],
  PodMonitor: ['podMonitorSelector', 'podMonitorNamespaceSelector'],
  Probe: ['probeSelector', 'probeNamespaceSelector'],
  ScrapeConfig: ['scrapeConfigSelector', 'scrapeConfigNamespaceSelector'],
  PrometheusRule: ['ruleSelector', 'ruleNamespaceSelector'],
  AlertmanagerConfig: ['alertmanagerConfigSelector', 'alertmanagerConfigNamespaceSelector'],
};

export function selectorFieldsFor(kind: SelectableKind): [string, string] {
  return SELECTOR_FIELDS[kind];
}

export type SelectionResult = 'selected' | 'not-selected' | 'unknown';

/**
 * Whether a workload (Prometheus, PrometheusAgent, ThanosRuler, Alertmanager)
 * picks up a configuration resource.
 *
 * Operator semantics:
 *  - resource selector nil  -> selects nothing; {} -> selects everything
 *  - namespace selector nil -> only the workload's own namespace; {} -> all
 *
 * `namespaceLabels` maps namespace name -> labels. When the namespace selector
 * is non-trivial and labels are not available, the result is 'unknown'.
 */
export function workloadSelects(
  workload: {
    metadata: { namespace?: string };
    spec?: PrometheusSpec | AlertmanagerSpec | ThanosRulerSpec;
  },
  kind: SelectableKind,
  resource: ObjectRef,
  namespaceLabels?: Record<string, Labels> | null
): SelectionResult {
  const spec = (workload.spec || {}) as Record<string, LabelSelector | null | undefined>;
  const [selField, nsField] = SELECTOR_FIELDS[kind];
  const selector = spec[selField];
  const nsSelector = spec[nsField];

  if (!matchesLabelSelector(selector, resource.metadata.labels, 'none')) {
    return 'not-selected';
  }

  const resourceNs = resource.metadata.namespace;
  if (nsSelector === null || nsSelector === undefined) {
    return resourceNs === workload.metadata.namespace ? 'selected' : 'not-selected';
  }
  const emptyNsSelector =
    Object.keys(nsSelector.matchLabels || {}).length === 0 &&
    (nsSelector.matchExpressions || []).length === 0;
  if (emptyNsSelector) return 'selected';

  if (!namespaceLabels || !resourceNs || !(resourceNs in namespaceLabels)) return 'unknown';
  return matchesLabelSelector(nsSelector, namespaceLabels[resourceNs])
    ? 'selected'
    : 'not-selected';
}

/** ServiceMonitor -> Service (namespaceSelector + selector on service labels). */
export function serviceMonitorMatchesService(
  sm: {
    metadata: { namespace?: string };
    spec?: { selector?: LabelSelector; namespaceSelector?: MonitorNamespaceSelector };
  },
  svc: ObjectRef
): boolean {
  if (
    !monitorNamespaceMatches(
      sm.metadata.namespace,
      sm.spec?.namespaceSelector,
      svc.metadata.namespace
    )
  ) {
    return false;
  }
  return matchesLabelSelector(sm.spec?.selector ?? {}, svc.metadata.labels);
}

/** PodMonitor -> Pod (same semantics as ServiceMonitor but on pod labels). */
export const podMonitorMatchesPod = serviceMonitorMatchesService;

/** Prometheus scrape pool prefix generated by the operator for each kind. */
export function scrapePoolPrefix(
  kind: 'ServiceMonitor' | 'PodMonitor' | 'Probe' | 'ScrapeConfig',
  namespace: string,
  name: string
): string {
  switch (kind) {
    case 'ServiceMonitor':
      return `serviceMonitor/${namespace}/${name}/`;
    case 'PodMonitor':
      return `podMonitor/${namespace}/${name}/`;
    case 'Probe':
      return `probe/${namespace}/${name}`;
    case 'ScrapeConfig':
      return `scrapeConfig/${namespace}/${name}`;
  }
}

export function targetsForResource(
  targets: PromTarget[],
  kind: 'ServiceMonitor' | 'PodMonitor' | 'Probe' | 'ScrapeConfig',
  namespace: string,
  name: string
): PromTarget[] {
  const prefix = scrapePoolPrefix(kind, namespace, name);
  return targets.filter(t =>
    kind === 'ServiceMonitor' || kind === 'PodMonitor'
      ? t.scrapePool.startsWith(prefix)
      : t.scrapePool === prefix || t.scrapePool.startsWith(`${prefix}/`)
  );
}

export interface TargetHealthSummary {
  up: number;
  down: number;
  unknown: number;
  total: number;
}

export function summarizeTargets(targets: PromTarget[]): TargetHealthSummary {
  const summary = { up: 0, down: 0, unknown: 0, total: targets.length };
  for (const t of targets) {
    if (t.health === 'up') summary.up++;
    else if (t.health === 'down') summary.down++;
    else summary.unknown++;
  }
  return summary;
}

/**
 * The operator writes each PrometheusRule into a file named
 * `<namespace>-<name>-<uid>.yaml`. Match on that basename.
 */
export function ruleGroupsForRule(
  groups: PromRuleGroup[],
  namespace: string,
  name: string,
  uid?: string
): PromRuleGroup[] {
  const exact = uid ? `${namespace}-${name}-${uid}.yaml` : null;
  const prefix = `${namespace}-${name}-`;
  return groups.filter(g => {
    const base = g.file.split('/').pop() || '';
    if (exact) return base === exact;
    return base.startsWith(prefix);
  });
}

/** Returns the rule-owning PrometheusRule (namespace/name) for a rule file, if recognisable. */
export function ruleFileOwner(
  file: string,
  rules: Array<{ metadata: { name: string; namespace?: string; uid?: string } }>
): { name: string; namespace: string } | null {
  const base = file.split('/').pop() || '';
  for (const r of rules) {
    const ns = r.metadata.namespace || '';
    if (r.metadata.uid && base === `${ns}-${r.metadata.name}-${r.metadata.uid}.yaml`) {
      return { name: r.metadata.name, namespace: ns };
    }
  }
  return null;
}

/** Alertmanagers a Prometheus sends alerts to (spec.alerting.alertmanagers). */
export function prometheusAlertmanagerServices(prom: {
  metadata: { namespace?: string };
  spec?: PrometheusSpec;
}): Array<{ namespace: string; name: string; port: string | number }> {
  return (prom.spec?.alerting?.alertmanagers || []).map(am => ({
    namespace: am.namespace || prom.metadata.namespace || '',
    name: am.name,
    port: am.port,
  }));
}

/**
 * Pod labels the operator puts on Prometheus/Alertmanager pods; used to find the
 * Service(s) that route to a given instance.
 */
export function instancePodLabels(kind: 'Prometheus' | 'Alertmanager', name: string): Labels {
  const app = kind === 'Prometheus' ? 'prometheus' : 'alertmanager';
  return {
    'app.kubernetes.io/name': app,
    'app.kubernetes.io/instance': name,
    'app.kubernetes.io/managed-by': 'prometheus-operator',
    'operator.prometheus.io/name': name,
    [app]: name,
  };
}

export function isHelmManaged(obj: {
  metadata: { labels?: Labels; annotations?: Labels };
}): boolean {
  return (
    obj.metadata.labels?.['app.kubernetes.io/managed-by'] === 'Helm' ||
    !!obj.metadata.annotations?.['meta.helm.sh/release-name']
  );
}

export function helmRelease(obj: {
  metadata: { labels?: Labels; annotations?: Labels };
}): string | null {
  return (
    obj.metadata.annotations?.['meta.helm.sh/release-name'] || obj.metadata.labels?.release || null
  );
}

/**
 * Labels that a new resource must carry to be picked up by the given workload
 * selector (e.g. kube-prometheus-stack's `release: <name>`). Only matchLabels
 * can be satisfied automatically.
 */
export function requiredLabelsFor(
  workload: { spec?: PrometheusSpec | AlertmanagerSpec },
  kind: SelectableKind
): Labels | null {
  const [selField] = SELECTOR_FIELDS[kind];
  const selector = (
    workload.spec as Record<string, LabelSelector | null | undefined> | undefined
  )?.[selField];
  if (selector === null || selector === undefined) return null;
  return { ...(selector.matchLabels || {}) };
}
